// Copies the runtime files of spec/ into extension/spec/ and writes extension/spec/spec.js,
// a generated classic script that sets globalThis.KOTIKO_SPEC (slice 09 section 1). The
// extension can't read files outside its folder and has no build step, so the copy is
// committed and CI checks it is current.
//
//   node spec/tools/sync-extension.mjs           write the copy
//   node spec/tools/sync-extension.mjs --check   exit 1 if the copy is stale
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const SPEC = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(path.dirname(SPEC), "extension", "spec");

const TOP = ["VERSION", "rules.json", "pronunciation.json", "prompt.md", "languages.json", "lang-aliases.json", "models.json", "providers.json", "wiktionary.json"];
const LANG_FILES = ["stopwords.txt", "stem.json", "variants.json", "respelling.json", "welcome.json", "sentences.json", "boundaries.json"];
// Copied but kept out of spec.js: about 200 KB that only the background reads, by fetch,
// when the learner's languages change (slice 50 section 5).
const COPY_ONLY = ["lang/_generic/stopwords.json"];

// REUSE-IgnoreStart
const HEADER =
  "// SPDX-FileCopyrightText: 2026 ScriptKittyOS and the Kotiko contributors\n" +
  "// SPDX-License-Identifier: Apache-2.0 AND Unicode-3.0\n\n";
// REUSE-IgnoreEnd

const read = (rel) => fs.readFileSync(path.join(SPEC, rel), "utf8");
const json = (rel) => JSON.parse(read(rel));
const stopwords = (text) =>
  text
    .split("\n")
    .map((l) => l.trim())
    .filter((l) => l && !l.startsWith("#"));

function expected() {
  const files = new Map();
  for (const f of TOP) files.set(f, read(f));
  const lang = {};
  const folders = fs
    .readdirSync(path.join(SPEC, "lang"), { withFileTypes: true })
    .filter((d) => d.isDirectory() && d.name !== "schema")
    .map((d) => d.name)
    .sort();
  for (const folder of folders) {
    lang[folder] = {};
    for (const f of LANG_FILES) {
      const rel = `lang/${folder}/${f}`;
      if (!fs.existsSync(path.join(SPEC, rel))) continue;
      files.set(rel, read(rel));
      const kind = f.replace(/\.(json|txt)$/, "");
      lang[folder][kind] = f.endsWith(".txt") ? stopwords(read(rel)) : json(rel);
    }
  }
  for (const rel of COPY_ONLY) files.set(rel, read(rel));
  const data = {
    version: read("VERSION").trim(),
    rules: json("rules.json"),
    pronunciation: json("pronunciation.json"),
    languages: json("languages.json"),
    aliases: json("lang-aliases.json"),
    models: json("models.json"),
    providers: json("providers.json"),
    wiktionary: json("wiktionary.json"),
    lang,
    prompt: read("prompt.md"),
  };
  files.set(
    "spec.js",
    HEADER +
      "// Generated by spec/tools/sync-extension.mjs from spec/. Do not edit: change spec/ and\n" +
      "// run `node spec/tools/sync-extension.mjs`. Language data derived from Unicode CLDR.\n" +
      "(() => {\n" +
      `  const SPEC = ${JSON.stringify(data)};\n` +
      '  if (typeof module !== "undefined" && module.exports) module.exports = SPEC;\n' +
      "  else globalThis.KOTIKO_SPEC = SPEC;\n" +
      "})();\n",
  );
  return files;
}

function existing() {
  const files = new Map();
  if (!fs.existsSync(OUT)) return files;
  const walk = (dir) => {
    for (const d of fs.readdirSync(dir, { withFileTypes: true })) {
      const full = path.join(dir, d.name);
      if (d.isDirectory()) walk(full);
      else files.set(path.relative(OUT, full).split(path.sep).join("/"), fs.readFileSync(full, "utf8"));
    }
  };
  walk(OUT);
  return files;
}

const want = expected();
const have = existing();

if (process.argv.includes("--check")) {
  const problems = [];
  for (const [rel, text] of want) if (have.get(rel) !== text) problems.push(`extension/spec/${rel} is stale or missing`);
  for (const rel of have.keys()) if (!want.has(rel)) problems.push(`extension/spec/${rel} isn't in spec/ any more`);
  if (problems.length) {
    console.error(problems.join("\n"));
    console.error("Run: node spec/tools/sync-extension.mjs");
    process.exit(1);
  }
  console.log(`extension/spec/ matches spec/ (${want.size} files).`);
} else {
  for (const rel of have.keys()) if (!want.has(rel)) fs.rmSync(path.join(OUT, rel));
  for (const [rel, text] of want) {
    fs.mkdirSync(path.dirname(path.join(OUT, rel)), { recursive: true });
    fs.writeFileSync(path.join(OUT, rel), text);
  }
  console.log(`Wrote extension/spec/ (${want.size} files).`);
}
